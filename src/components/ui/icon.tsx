export type IconName = keyof typeof iconMap;

export type IconProps = Omit<ComponentPropsWithoutRef<"svg">, "name" | "strokeWidth" | "children"> & {
  name: IconName;
  size?: number;
};

export function Icon({ name, size, "aria-label": ariaLabel, "aria-hidden": ariaHidden, role, ...props }: IconProps) {
  const Component = iconMap[name];
  // Labelled icons are announced; decorative ones stay hidden unless the caller says otherwise.
  const hidden = ariaHidden ?? (ariaLabel ? undefined : true);

  return (
    <Component
      size={size}
      stroke={2}
      aria-hidden={hidden}
      aria-label={ariaLabel}
      role={role ?? (ariaLabel ? "img" : undefined)}
      {...props}
    />
  );
}
